"""One entry point for the Glimmer planner fine-tune. Runbook: docs/private/glimmer/finetune.md.

  python -m training.glimmer split    --run-id v1        # pool + held-out split (app venv ok)
  python -m training.glimmer label    --run-id v1        # verified plans for the train split (hours; resumable)
  python -m training.glimmer build    --run-id v1        # train.jsonl / val.jsonl + yield
  python -m training.glimmer prepare  --run-id v1        # render with the Glimmer tokenizer, token counts (glimmer venv)
  python -m training.glimmer train    --run-id v1        # free serverless LoRA SFT, no sampling (glimmer venv)
  python -m training.glimmer archive  --run-id v1        # private copy of the datasets in the Fireworks account
  python -m training.glimmer compare  --run-id v1 --mode tuned --limit 5     # BILLABLE: smoke test
  python -m training.glimmer compare  --run-id v1 --mode base|tuned [--subset eval]   # BILLABLE
  python -m training.glimmer trial    --run-id v1 --data public|private [--spark]     # BILLABLE (glimmer)
  python -m training.glimmer report   --run-id v1        # chart + ledger + results block in the runbook

Every step is idempotent (re-running skips finished work, or resumes) and records itself in
evals/private/glimmer/<run_id>/manifest.json, with a sanitised copy in docs/private/glimmer/runs/.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from training.glimmer import common  # noqa: E402



def report(run_id: str) -> None:
    from training.glimmer.evaluate import ledger_summary, write_chart

    start, end = f"<!-- results:{run_id}:start -->", f"<!-- results:{run_id}:end -->"
    chart = write_chart(run_id)
    ledger = ledger_summary()
    m = common.update_manifest(run_id, "ledger", ledger)
    if chart:
        m = common.update_manifest(run_id, "chart", {"path": chart})
    lines = [start, f"### Run `{run_id}` (generated by `python -m training.glimmer report`)", ""]
    b = m.get("build") or {}
    if b:
        lines.append(f"- Training pairs: {b['train']['n']} train, {b['val']['n']} validation "
                     f"(from {b['labelled']} labelled questions; outcomes {json.dumps(b['outcomes'])}).")
    t = m.get("train") or {}
    if t:
        losses = t.get("losses") or [{}]
        lines.append(f"- Training: {t.get('steps')} steps, LoRA rank {t['hyper']['lora_rank']}, "
                     f"loss {losses[0].get('loss')} -> {losses[-1].get('loss')}, adapter `{t.get('adapter_model')}`.")
    for name, e in sorted((m.get("eval") or {}).items()):
        lines.append(f"- Eval `{name}`: n={e['n']}, valid JSON {e['json']}, passes gate {e['gate']}, correct {e['correct']}, "
                     f"wrong but passed gate {e['wrong_shown']}, p50 {e['p50_seconds']} s, p90 {e['p90_seconds']} s, ${e['usd']}.")
    for name, tr in sorted((m.get("trial") or {}).items()):
        lines.append(f"- Planner trial `{name}`: {tr.get('correct')}/{tr.get('n')} correct, WRONG {tr.get('wrong')}, "
                     f"declined {tr.get('declined')}, p50 {tr.get('p50_seconds')} s, p90 {tr.get('p90_seconds')} s.")
    if chart:
        lines += ["", f"![base vs tuned]({Path(chart).name})"]
    lines += ["", "#### Sampling ledger (all billable Glimmer calls, estimated at list price)", "",
              "| batch | calls | prompt tokens | sampled tokens | est. USD |", "|---|---|---|---|---|"]
    for tag, r in sorted(ledger["by_batch"].items()):
        lines.append(f"| {tag} | {r['calls']} | {r['prompt_tokens']} | {r['sampled_tokens']} | {r['usd']:.4f} |")
    lines += [f"| **total** | {ledger['calls']} | | | **{ledger['total_usd']:.4f}** |", "", end]
    doc = common.DOCS / "finetune.md"
    text = doc.read_text(encoding="utf-8")
    block = "\n".join(lines)
    anchor = "## Changes between runs"
    if start in text:
        text = re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: block, text, flags=re.S)
    elif anchor in text:
        text = text.replace(anchor, block + "\n\n" + anchor)
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    doc.write_text(text, encoding="utf-8")
    # The full runbook copy also lives with the private record.
    (common.GLIMMER / "finetune.md").write_text(text, encoding="utf-8")
    print(f"report updated: {doc.relative_to(ROOT)}")


def main() -> int:
    ap = argparse.ArgumentParser(prog="python -m training.glimmer")
    ap.add_argument("step", choices=["split", "label", "build", "prepare", "train", "archive", "compare", "trial", "report"])
    ap.add_argument("--run-id", default="v1")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--workers", type=int, default=None)
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--mode", choices=["base", "tuned"], default="tuned")
    ap.add_argument("--subset", choices=["all", "eval", "papers"], default="all")
    ap.add_argument("--data", choices=["public", "private"], default="public")
    ap.add_argument("--spark", action="store_true", help="trial: the Spark-only baseline (no Glimmer, not billable)")
    for k, v in {"epochs": 2, "lora_rank": 8, "batch_size": 16}.items():
        ap.add_argument(f"--{k.replace('_', '-')}", type=int, default=None)
    ap.add_argument("--lr", type=float, default=None)
    args = ap.parse_args()
    common.load_env()

    if args.step == "split":
        from training.glimmer.split import run
        run(args.run_id, force=args.force)
    elif args.step == "label":
        from training.glimmer.label import run_label
        run_label(args.run_id, workers=args.workers or 10, limit=args.limit)
    elif args.step == "build":
        from training.glimmer.label import run_build
        run_build(args.run_id)
    elif args.step in ("prepare", "train"):
        from training.glimmer.train import HYPER, run_prepare, run_train
        hyper = json.loads(json.dumps(HYPER))
        for k in ("epochs", "lora_rank", "batch_size"):
            if getattr(args, k) is not None:
                hyper[k] = getattr(args, k)
        if args.lr is not None:
            hyper["learning_rate"] = args.lr
        if args.step == "prepare":
            common.update_manifest(args.run_id, "prepare", {"finished": common.now(), **run_prepare(args.run_id, hyper)})
        else:
            run_train(args.run_id, hyper, force=args.force)
    elif args.step == "archive":
        from training.glimmer.train import run_archive
        run_archive(args.run_id)
    elif args.step == "compare":
        from training.glimmer.evaluate import run_compare
        run_compare(args.run_id, args.mode, args.subset, args.limit, workers=args.workers or 4)
    elif args.step == "trial":
        from training.glimmer.evaluate import run_trial
        run_trial(args.run_id, args.data, glimmer=not args.spark, workers=args.workers or 4)
    elif args.step == "report":
        report(args.run_id)
    return 0


if __name__ == "__main__":
    sys.exit(main())
